"""Write the MiSTer MRA that loads the four shape PROMs.

The MRA tells the MiSTer to send the PROM dumps from fonz.zip to the core as
one download (ioctl index 0). The order and offsets here must match
rtl/fonz_prom_load.v and the BASE parameters in rtl/fonz_upper_shape.v
and rtl/fonz_lower_shape.v. Bytes are sent exactly as dumped: Q1 in bit 0,
Q4 in bit 3. The Q4..Q1 -> C0..C3 reversal is done in the multiplexer RTL.

    python scripts/make_mra.py            write mra/The Fonz.mra
    python scripts/make_mra.py --check    fail if the checked-in MRA differs
    python scripts/make_mra.py --bin FILE also write the assembled download
"""
import argparse
import hashlib
import pathlib
import sys
import zipfile
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from extract_proms import PROMS  # noqa: E402  (sizes and SHA-1 of each dump)

ZIP = 'fonz.zip'
SETNAME = 'fonz'
RBF = 'Fonz'
MRA = ROOT / 'mra' / 'The Fonz.mra'

# (dump name, board position, download offset)
LAYOUT = [
    ('ic86.86', 'IC86', 0x000),
    ('ic87.87', 'IC87', 0x200),
    ('pr-09.49', 'IC49', 0x400),
    ('pr-08.50', 'IC50', 0x500),
]


def read_dumps(zip_path=ROOT / ZIP):
    """Return {name: bytes}, checked against extract_proms.PROMS."""
    dumps = {}
    with zipfile.ZipFile(zip_path) as archive:
        for name, _, _ in LAYOUT:
            size, digest = PROMS[name]
            data = archive.read(name)
            if len(data) != size or hashlib.sha1(data).hexdigest() != digest:
                raise ValueError(f'{name}: unexpected ROM dump')
            dumps[name] = data
    return dumps


def assemble(dumps):
    """The byte stream the MiSTer sends for this MRA."""
    image = bytearray()
    for name, _, offset in LAYOUT:
        if len(image) != offset:
            raise ValueError(f'{name}: layout gap at {len(image):#x}')
        image += dumps[name]
    return bytes(image)


def render(dumps):
    image = assemble(dumps)
    lines = [
        '<misterromdescription>',
        '    <name>The Fonz</name>',
        f'    <setname>{SETNAME}</setname>',
        f'    <rbf>{RBF}</rbf>',
        '    <mameversion>0000</mameversion>',
        '    <year>1976</year>',
        '    <manufacturer>Sega</manufacturer>',
        '    <category>Driving</category>',
        '    <!-- Generated by scripts/make_mra.py; do not edit by hand. -->',
        '    <!-- Shape PROMs, one nibble per byte, Q1 in bit 0, as dumped. -->',
        f'    <rom index="0" zip="{ZIP}" md5="{hashlib.md5(image).hexdigest()}">',
    ]
    for name, position, offset in LAYOUT:
        crc = zlib.crc32(dumps[name])
        lines.append(f'        <!-- {offset:#05x} {position} -->')
        lines.append(f'        <part name="{name}" crc="{crc:08x}"/>')
    lines += ['    </rom>']
    # Button names for MiSTer's joystick menu, in the core's input-bit order
    # (the J1 line of mister/Fonz.sv): button 1 (bit 4) is the full-throttle button, button 2
    # (bit 5) is unused, then Start (bit 6) and Coin (bit 7). Without this
    # element MiSTer lists the inputs as A, B, X, Y. The default pad buttons
    # follow the named inputs only. R2 is the variable throttle on its own path (joytrig), so it is
    # not a button here. There is no Pause: the board has no way to stop.
    lines += [
        '    <buttons names="Accelerate,-,Start,Coin" default="A,Start,Select" count="1"/>',
    ]
    # No <switches>: the board has no DIP switches, and the core's options
    # are in the OSD (CONF_STR in mister/Fonz.sv).
    lines += ['</misterromdescription>', '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--bin', type=pathlib.Path)
    args = parser.parse_args(argv)
    dumps = read_dumps()
    text = render(dumps)
    if args.bin:
        args.bin.write_bytes(assemble(dumps))
    if args.check:
        current = MRA.read_text(encoding='ascii') if MRA.exists() else None
        if current != text:
            print(f'{MRA.relative_to(ROOT)} is out of date; run scripts/make_mra.py')
            return 1
        print(f'{MRA.relative_to(ROOT)} matches the script output')
        return 0
    MRA.parent.mkdir(exist_ok=True)
    MRA.write_text(text, encoding='ascii', newline='\n')
    print(f'wrote {MRA.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
