#!/usr/bin/env python3
"""IC9 / IC106 shape oscillator: constants for the synthesisable model.

Writes rtl/analog/fonz_shape_osc_table.vh: the half-period lookup
(trigger delay + 74123 pulse width, against control voltage) and the
fixed-point coefficients of the control network, for a 1 us step.

The formulas are the ones in rtl/analog/fonz_shape_oscillator_ref.v;
keep the two in step. Component values and the unknown pot settings are
the defaults below. The coefficients that depend on VR1 / VR9 (bike size)
and VR2 (all bikes) are written for every setting the OSD offers
(scripts/pot_settings.py), as functions of the setting's code; code 0 is
the factory setting. --table prints the frequency range as Markdown.

    python scripts/shape_osc_table.py [--table]
"""
import argparse
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import pot_settings  # noqa: E402
OUT = ROOT / 'rtl' / 'analog' / 'fonz_shape_osc_table.vh'

# IC9 names, IC106 names in brackets. Values identical on both copies.
R_SERIES = 2200.0      # R7 [R99]
R_COUPLE = 3300.0      # R8 [R102]
C_COUPLE = 22e-6       # C11 [C66]
C_HOLD = 2.2e-6        # C10 [C81]
R_BASE = 33000.0       # R6 [R103]
R_EMITTER = 2200.0     # R4 [R105]
R_P = 1e12             # P1 [P6], not identified: taken as absent
R_PULLUP = 68000.0     # R5 [R104]
BETA = 100.0
VBE = 0.65
VDIODE = 0.65
RDIODE = 10.0
VOL_OC = 0.2
VCESAT = 0.2
VCC = 5.0
C_TIMING = 10e-12
C_INTERNAL = 19.29e-12  # '123 small-C line, see the reference model
R_INTERNAL = 700.0
V_THRESHOLD = 1.22
T_INTRINSIC = 9.72     # ns
TPD_NS = 22.0
STEP = 1e-6            # control network step, s

LUT_SHIFT = 14         # index = control voltage in uV >> 14 (16.4 mV steps)
LUT_SIZE = 320         # 0 .. 5.24 V
Q = 32                 # coefficient fraction bits


def r_emitter_path():
    return R_EMITTER * R_P / (R_EMITTER + R_P) + R_BASE / (BETA + 1.0)


def width_ns(vcontrol):
    c = C_TIMING + C_INTERNAL
    rp = r_emitter_path()
    vs = vcontrol - VBE
    if vs <= 0.0:
        t = (R_PULLUP + R_INTERNAL) * c * math.log(VCC / (VCC - V_THRESHOLD))
    else:
        req = 1.0 / (1.0 / R_PULLUP + 1.0 / rp)
        veq = (VCC / R_PULLUP + vs / rp) * req
        if vs >= V_THRESHOLD:
            t = (req + R_INTERNAL) * c * math.log(veq / (veq - V_THRESHOLD))
        else:
            t = ((req + R_INTERNAL) * c * math.log(veq / (veq - vs))
                 + (R_PULLUP + R_INTERNAL) * c
                 * math.log((VCC - vs) / (VCC - V_THRESHOLD)))
    return T_INTRINSIC + t * 1e9


def half_period_ns(vcontrol):
    return TPD_NS + width_ns(vcontrol)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--table', action='store_true', help='print the range as Markdown')
    args = ap.parse_args()

    def q(x):
        return int(round(x * (1 << Q)))

    def coefs(vr, vr2):
        rv = vr + R_SERIES
        rs = vr2 + RDIODE
        g = 1.0 / rv + 1.0 / R_COUPLE + 1.0 / rs
        return {
            'K_Y_RC': STEP / (C_HOLD * R_COUPLE),
            'K_Y_RV': STEP / (C_HOLD * rv),
            'K_Y_RS': STEP / (C_HOLD * rs),
            'K_Y_IB': STEP / (C_HOLD * r_emitter_path() * (BETA + 1.0)),
            'K_C_RC': STEP / (C_COUPLE * R_COUPLE),
            'K_C_RS': STEP / (C_COUPLE * rs),
            'K_C_LOOP': STEP / (C_COUPLE * (rv + R_COUPLE)),
            'G1': (1.0 / R_COUPLE) / g,
            'G2': (1.0 / rs) / g,
        }
    volts = {
        'V_SRC': VCC - VCESAT - VDIODE,
        'V_OL': VOL_OC,
        'V_IB0': VBE + V_THRESHOLD / 2.0,
    }
    pots = {p[0]: pot_settings.codes(p) for p in pot_settings.POTS}
    if pots['VR1'] != pots['VR9']:
        raise SystemExit('VR1 and VR9 must offer the same settings (one table for both)')
    bike, all_bikes = pots['VR1'], pots['VR2']
    base = coefs(bike[0], all_bikes[0])

    lines = [
        '// Generated by scripts/shape_osc_table.py; do not edit.',
        f'// Step 1 us. Coefficients are Q{Q} (G1: Q30, 1 - G2: Q29); voltages in microvolts.',
        f'// Factory setting (code 0): VR1/VR9 = {bike[0]} ohm, VR2 = {all_bikes[0]} ohm.',
        '// The coefficients set by VR1/VR9 (code vr) and VR2 (code vr2) are',
        '// functions of the OSD codes (scripts/pot_settings.py).',
    ]
    for k in ('K_Y_RC', 'K_Y_IB', 'K_C_RC'):
        lines.append(f"localparam signed [63:0] {k} = 64'sd{q(base[k])};  // {base[k]:.6g}")

    def table(name, width, entries, args_decl, sel, sel_w):
        lines.append(f'function [{width - 1}:0] {name}({args_decl});')
        lines.append(f'    case ({sel})')
        for code, value, note in entries:
            if value >= (1 << width):
                raise SystemExit(f'{name}: {value} does not fit {width} bits')
            lines.append(f"    {sel_w}'d{code}: {name} = {width}'d{value};  // {note}")
        lines.append(f"    default: {name} = {width}'d{entries[0][1]};")
        lines.append('    endcase')
        lines.append('endfunction')

    one = 'input [2:0] vr'
    table('k_y_rv', 26, [(i, q(coefs(v, all_bikes[0])['K_Y_RV']), f'VR {v}') for i, v in enumerate(bike)],
          one, 'vr', 3)
    table('k_c_loop', 26, [(i, q(coefs(v, all_bikes[0])['K_C_LOOP']), f'VR {v}') for i, v in enumerate(bike)],
          one, 'vr', 3)
    table('k_y_rs', 26, [(i, q(coefs(bike[0], v)['K_Y_RS']), f'VR2 {v}') for i, v in enumerate(all_bikes)],
          'input [2:0] vr2', 'vr2', 3)
    table('k_c_rs', 26, [(i, q(coefs(bike[0], v)['K_C_RS']), f'VR2 {v}') for i, v in enumerate(all_bikes)],
          'input [2:0] vr2', 'vr2', 3)
    g1, g2c = [], []
    for i, v in enumerate(bike):
        for j, v2 in enumerate(all_bikes):
            c = coefs(v, v2)
            g1.append(((i << 3) | j, (q(c['G1']) + 2) >> 2, f'VR {v}, VR2 {v2}'))
            g2c.append(((i << 3) | j, ((1 << Q) - q(c['G2']) + 4) >> 3, f'VR {v}, VR2 {v2}'))
    table('g1_q30', 26, g1, 'input [2:0] vr, input [2:0] vr2', '{vr, vr2}', 6)
    table('g2c_q29', 26, g2c, 'input [2:0] vr, input [2:0] vr2', '{vr, vr2}', 6)
    for k, v in volts.items():
        lines.append(f"localparam signed [31:0] {k} = 32'sd{int(round(v * 1e6))};")
    lines.append(f'localparam integer LUT_SHIFT = {LUT_SHIFT};')
    lines.append(f'localparam integer LUT_SIZE = {LUT_SIZE};')
    lines.append('// Half period (trigger delay + pulse width) in ns x 16, index = uV >> LUT_SHIFT.')
    lines.append('function [15:0] half_period_ns_x16(input [8:0] index);')
    lines.append('    case (index)')
    for i in range(LUT_SIZE):
        v = ((i << LUT_SHIFT) + (1 << (LUT_SHIFT - 1))) * 1e-6
        lines.append(f"    9'd{i}: half_period_ns_x16 = 16'd{int(round(half_period_ns(v) * 16))};")
    v = (LUT_SIZE << LUT_SHIFT) * 1e-6
    lines.append(f"    default: half_period_ns_x16 = 16'd{int(round(half_period_ns(v) * 16))};")
    lines.append('    endcase')
    lines.append('endfunction')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}')

    if args.table:
        print('| Control voltage | Pulse width | Period | Frequency |')
        print('|---|---|---|---|')
        for i in range(0, 19):
            v = i * 0.25
            hp = half_period_ns(v)
            print(f'| {v:.2f} V | {width_ns(v):.0f} ns | {2 * hp:.0f} ns | {1e3 / (2 * hp):.2f} MHz |')


if __name__ == '__main__':
    main()
