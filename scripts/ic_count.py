"""Count the IC types on The Fonz board from the chip list.

The chip list is a comment block in rtl/fonz_board.v, one line per IC,
sorted by IC number:

    // IC2    74161
    // IC28   74393   marked "392/B" on the drawing

This script writes the IC-type count block that follows it, so the count
cannot drift from the list. It also checks that the list is sorted, has no
repeats, and names every IC that appears in a wire name (ICnn_pin...) in
rtl/fonz_*.v, and that the RTL mentions every listed IC.

Run from the repository root:  python scripts/ic_count.py
Add --check to fail (exit 1) when the count block is out of date or a check
fails, instead of rewriting the file.
"""
import pathlib
import re
import sys
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[1]
BOARD = ROOT / 'rtl' / 'fonz_board.v'
LIST_BEGIN = '// ---- chip list: begin ----'
LIST_END = '// ---- chip list: end ----'
COUNT_BEGIN = '// ---- IC-type count (generated by scripts/ic_count.py; do not edit): begin ----'
COUNT_END = '// ---- IC-type count: end ----'
ENTRY = re.compile(r'//\s+IC(\d+)\s+(\S+)(?:\s+(.*))?$')
WIRE_IC = re.compile(r'\bIC(\d+)_pin')
ANY_IC = re.compile(r'\b(?:IC|ic)(\d+)(?=[_a-z.\s(,]|$)')


def block(text, begin, end):
    try:
        a = text.index(begin) + len(begin)
        b = text.index(end, a)
    except ValueError:
        raise SystemExit(f'{BOARD.name}: markers "{begin}" / "{end}" not found')
    return a, b


def read_list(text):
    a, b = block(text, LIST_BEGIN, LIST_END)
    chips = []
    for line in text[a:b].strip('\n').split('\n'):
        m = ENTRY.match(line.strip())
        if not m:
            raise SystemExit(f'chip list: cannot read "{line.strip()}"')
        chips.append((int(m.group(1)), m.group(2)))
    return chips


def count_block(chips):
    counts = Counter(t for _, t in chips)
    numbers = {}
    for n, t in chips:
        numbers.setdefault(t, []).append(n)
    width = max(len(t) for t in counts)
    lines = [f'// {len(chips)} ICs, {len(counts)} types.']
    for t, c in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        ics = ' '.join(str(n) for n in numbers[t])
        lines.append(f'// {t:<{width}}  x{c:<2}  IC {ics}')
    return '\n' + '\n'.join(lines) + '\n'


def checks(chips):
    errors = []
    nums = [n for n, _ in chips]
    if nums != sorted(nums):
        errors.append('chip list is not sorted by IC number')
    repeats = sorted(n for n, c in Counter(nums).items() if c > 1)
    if repeats:
        errors.append('chip list repeats IC ' + ', '.join(map(str, repeats)))
    used, mentioned = set(), set()
    for path in sorted(p for p in (ROOT / 'rtl').glob('fonz_*.v') if p.name != 'fonz_cabinet_inputs.v'):
        text = path.read_text(encoding='utf-8')
        if path == BOARD:  # the list itself does not count as a use
            text = text[:text.index(LIST_BEGIN)] + text[text.index(COUNT_END):]
        used |= {int(n) for n in WIRE_IC.findall(text)}
        mentioned |= {int(n) for n in ANY_IC.findall(text)}
    missing = sorted(used - set(nums))
    if missing:
        errors.append('wire names use ICs missing from the chip list: ' +
                      ', '.join(map(str, missing)))
    # A package modelled only as terms of a wired net (IC53..57) or named in
    # a comment (IC35) has no wire of its own, so any mention counts here.
    unused = sorted(set(nums) - used - mentioned)
    if unused:
        errors.append('listed ICs that the RTL never mentions: ' + ', '.join(map(str, unused)))
    return errors


def main():
    check = '--check' in sys.argv[1:]
    text = BOARD.read_text(encoding='utf-8')
    chips = read_list(text)
    errors = checks(chips)
    a, b = block(text, COUNT_BEGIN, COUNT_END)
    new = text[:a] + count_block(chips) + text[b:]
    stale = new != text
    if stale and not check:
        BOARD.write_text(new, encoding='utf-8', newline='\n')
    for e in errors:
        print(e)
    if check and stale:
        print('IC-type count is out of date; run: python scripts/ic_count.py')
    print(f'{len(chips)} ICs, {len(set(t for _, t in chips))} types'
          + ('' if not stale else (' (count stale)' if check else ' (count rewritten)')))
    return int(bool(errors) or (check and stale))


if __name__ == '__main__':
    raise SystemExit(main())
