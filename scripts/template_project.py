def rtl_files():
    by_name = {}
    for p in sorted((ROOT / 'rtl').rglob('*.v')):
        if p.name in by_name:
            raise SystemExit(f'two rtl files named {p.name}')
        by_name[p.name] = p
    out = []
    for n in RTL_FILES:
        if n not in by_name:
            raise SystemExit(f'RTL_FILES names {n}, which is not in rtl/')
        out.append(by_name[n].relative_to(ROOT).as_posix())
    return out + EXTRA


def render_qip():
    lines = [
        '# Generated by scripts/template_project.py; do not edit by hand.',
        '# Paths are relative to mister/.',
        '#',
        '# The clock the core runs at (rtl/pll: 57.22 MHz, 4 x the 14.305 MHz',
        '# crystal), for the edge-node delays of fonz_rc_edge_ce.',
        f'set_global_assignment -name VERILOG_MACRO "FONZ_CLK_SYS_HZ={CLK_SYS_HZ}"',
        '# The PROMs come from the MRA download, not from hex files',
        'set_global_assignment -name VERILOG_MACRO "FONZ_NO_PROM_INIT=1"',
        '# The .vh tables (pot settings, oscillator and road widths)',
        'set_global_assignment -name SEARCH_PATH ../rtl/analog',
    ]
    for f in rtl_files():
        lines.append(f'set_global_assignment -name VERILOG_FILE ../{f}')
    lines += [
        '# Multicycle paths of the analogue models',
        'set_global_assignment -name SDC_FILE analog_multicycle.sdc',
        'set_global_assignment -name SDC_FILE Fonz.sdc',
        'set_global_assignment -name SYSTEMVERILOG_FILE Fonz.sv',
        '',
    ]
    return '\n'.join(lines)


def blob_hash(path):
    data = path.read_bytes()
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


def check_sys():
    """Return a list of differences between mister/sys and the manifest."""
    want = {}
    for line in MANIFEST.read_text(encoding='utf-8').splitlines():
        meta, path = line.split('\t', 1)
        want[path] = meta.split()[2]
    have = {p.relative_to(MISTER).as_posix(): p
            for p in (MISTER / 'sys').rglob('*') if p.is_file()}
    errors = []
    for path, sha in sorted(want.items()):
        if path not in have:
            errors.append(f'missing {path}')
        elif blob_hash(have[path]) != sha:
            errors.append(f'changed {path}')
    errors += [f'not in the template: {p}' for p in sorted(set(have) - set(want))]
    return errors


def sync(checkout):
    rev = REV_FILE.read_text().strip()
    head = subprocess.check_output(['git', '-C', str(checkout), 'rev-parse', 'HEAD'], text=True).strip()
    if head != rev:
        raise SystemExit(f'{checkout} is at {head}, TEMPLATE_REVISION says {rev}')
    shutil.rmtree(MISTER / 'sys', ignore_errors=True)
    # The committed bytes: no eol conversion (core.autocrlf is often on under
    # Windows, and git archive applies it)
    tar = subprocess.run(['git', '-c', 'core.autocrlf=false', '-c', 'core.eol=lf',
                          '-C', str(checkout), 'archive', '--format=tar', rev, 'sys'],
                         check=True, capture_output=True).stdout
    with tarfile.open(fileobj=io.BytesIO(tar)) as archive:
        for member in archive.getmembers():
            if not member.isfile():
                continue
            dest = MISTER / member.name
            if MISTER.resolve() not in dest.resolve().parents:
                raise SystemExit(f'unexpected path in the archive: {member.name}')
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(archive.extractfile(member).read())
    tree = subprocess.check_output(['git', '-C', str(checkout), 'ls-tree', '-r', rev, 'sys'], text=True)
    MANIFEST.write_text(tree, encoding='utf-8', newline='\n')
    print(f'copied sys/ at {rev} and wrote {MANIFEST.relative_to(ROOT)}')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--sync', type=pathlib.Path, metavar='DIR')
    args = ap.parse_args(argv)
    if args.sync:
        sync(args.sync)
    text = render_qip()
    if not args.check:
        if not QIP.exists() or QIP.read_text(encoding='utf-8') != text:
            QIP.write_text(text, encoding='utf-8', newline='\n')
            print(f'wrote {QIP.relative_to(ROOT)}')
        return 0
    errors = []
    if not QIP.exists() or QIP.read_text(encoding='utf-8') != text:
        errors.append(f'{QIP.relative_to(ROOT)} is stale; run scripts/template_project.py')
    for f in rtl_files():
        if not (ROOT / f).exists():
            errors.append(f'missing {f}')
    errors += check_sys()
    for e in errors:
        print('FAIL:', e)
    if errors:
        return 1
    n = len(MANIFEST.read_text(encoding='utf-8').splitlines())
    print(f'PASS: files.qip up to date; mister/sys matches Template_MiSTer '
          f'{REV_FILE.read_text().strip()[:7]} ({n} files)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
