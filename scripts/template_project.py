#!/usr/bin/env python3
"""The Template_MiSTer project in mister/: write its file list and check its
framework copy.

    python scripts/template_project.py            write mister/files.qip
    python scripts/template_project.py --check    fail if mister/files.qip is
                                                  stale or mister/sys/ differs
                                                  from the pinned template
    python scripts/template_project.py --sync DIR copy sys/ from a
                                                  Template_MiSTer checkout at
                                                  TEMPLATE_REVISION, and write
                                                  mister/TEMPLATE_SYS.txt

mister/files.qip lists the rtl/ files of RTL_FILES below (by file name;
each name is unique under rtl/), plus rtl/mister/fonz_core.v, the timing
constraints and mister/Fonz.sv. Quartus reads them in place: nothing is
copied.

mister/sys/ is MiSTer-devel's Template_MiSTer sys/ folder at the commit in
TEMPLATE_REVISION, byte for byte (.gitattributes keeps git from changing its
line endings). mister/TEMPLATE_SYS.txt is `git ls-tree -r REV sys` of that
commit; --check compares the git blob hash of every file in mister/sys/
with it, so it needs no network. To move to a newer template: check it out,
write its commit to TEMPLATE_REVISION and run --sync on the checkout.
"""
