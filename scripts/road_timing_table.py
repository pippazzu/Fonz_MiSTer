#!/usr/bin/env python3
"""Road monostables: width tables for the synthesisable road model.

Writes rtl/analog/fonz_road_timing_table.vh, used by
rtl/analog/fonz_road_timing.v. For each of the three transistor-fed
Rext networks it tabulates the 'LS123 pulse width against the transistor's
base voltage, using the formula of the reference model
rtl/analog/fonz_road_timing_ref.v (function `cycles`); keep the two in
step. The control networks themselves are in the Verilog, with integer
coefficients worked out at elaboration from the pot parameters.

Each entry holds the width at the start of a 16.4 mV step and the change
to the next entry, so the Verilog interpolates linearly inside the step.
Widths are in quarter nanoseconds, clamped to 24 bits (4.19 ms; any width
over a line, 63.5 us, never ends before the next trigger anyway).

    python scripts/road_timing_table.py [--check]
"""
import argparse
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'rtl' / 'analog' / 'fonz_road_timing_table.vh'

VCC, VBE, VTH = 5.0, 0.65, 1.2
LUT_SHIFT = 14          # index = base voltage in uV >> 14 (16.4 mV)
LUT_SIZE = 320          # 0 .. 5.24 V
W_MAX = (1 << 24) - 1   # quarter ns


def k_ls(c):
    """'LS123 K(Cext), TI SDLS043 Figure 7, as k_ls in the reference."""
    pf = c * 1e12
    if pf <= 100.0:
        return 0.495
    if pf <= 200.0:
        return 0.495 - (pf - 100.0) * 0.065 / 100.0
    if pf <= 500.0:
        return 0.430 - (pf - 200.0) * 0.045 / 300.0
    if pf <= 1000.0:
        return 0.385 - (pf - 500.0) * 0.020 / 500.0
    if pf <= 2000.0:
        return 0.365 - (pf - 1000.0) * 0.017 / 1000.0
    if pf <= 5000.0:
        return 0.348 - (pf - 2000.0) * 0.013 / 3000.0
    if pf <= 10000.0:
        return 0.335 - (pf - 5000.0) * 0.008 / 5000.0
    if pf <= 1.0e6:
        return 0.327 + (pf - 10000.0) * 0.003 / 990000.0
    return 0.330


def width_s(v_base, r, r_pull, c):
    """The reference model's `cycles`, in seconds."""
    tau = r * k_ls(c) * c / math.log(VCC / (VCC - VTH))
    vt = v_base - VBE
    a = r / (r + r_pull) if r_pull > 0.0 else 0.0
    if ((vt - VCC * a) / (1.0 - a) >= VTH) if r_pull > 0.0 else (vt >= VTH + 0.02):
        return tau * math.log(vt / (vt - VTH))
    if r_pull > 0.0:
        v1 = (vt - VCC * a) / (1.0 - a)
        if v1 > 0.0:
            t1 = tau * math.log(vt / (vt - v1))
        else:
            t1, v1 = 0.0, 0.0
        t2 = tau / a * math.log((VCC - v1) / (VCC - VTH))
        return t1 + t2
    return 1.0


# name, emitter resistor (select resistor not fitted), emitter pull-up, Cext
TABLES = [
    ('W97B', 1000.0, 0.0, 44.0e-9),     # TR5, R40, C27 || C28
    ('W102A', 2200.0, 100.0e3, 9.4e-9),  # TR6, R58, R57, C42 || C43
    ('WKERB', 3300.0, 68.0e3, 100e-12),  # TR7 / TR8, R72 / R98, R71 / R97, 100 pF
]


def q4(v_uv, r, r_pull, c):
    return min(W_MAX, int(round(width_s(v_uv * 1e-6, r, r_pull, c) * 4e9)))


def generate():
    lines = [
        '// Generated by scripts/road_timing_table.py; do not edit.',
        "// 'LS123 width against base voltage for the road's transistor-fed",
        '// stages. Entry i: {width at (i << LUT_SHIFT) uV, change to entry i+1},',
        '// widths in quarter ns. Selector: 0 = IC97B (TR5), 1 = IC102A (TR6),',
        '// 2 = IC102B / IC104B (TR7 / TR8).',
        f'localparam integer ROAD_LUT_SHIFT = {LUT_SHIFT};',
        f'localparam integer ROAD_LUT_SIZE = {LUT_SIZE};',
        'function [47:0] road_width_entry(input [1:0] sel, input [8:0] index);',
        '    case ({sel, index})',
    ]
    for t, (name, r, r_pull, c) in enumerate(TABLES):
        lines.append(f'    // {name}: Re {r:.0f} ohm, pull-up {r_pull:.0f} ohm, Cext {c * 1e12:.0f} pF')
        for i in range(LUT_SIZE + 1):
            w0 = q4(i << LUT_SHIFT, r, r_pull, c)
            w1 = q4((i + 1) << LUT_SHIFT, r, r_pull, c)
            d = w1 - w0
            dd = d & ((1 << 24) - 1)
            idx = min(i, LUT_SIZE)
            lines.append(f"    {{2'd{t}, 9'd{idx}}}: road_width_entry = {{24'd{w0}, 24'h{dd:06x}}};")
    last = q4(LUT_SIZE << LUT_SHIFT, *TABLES[0][1:])
    lines.append(f"    default: road_width_entry = {{24'd{last}, 24'h000000}};")
    lines.append('    endcase')
    lines.append('endfunction')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true',
                    help='fail if the table on disk is out of date')
    args = ap.parse_args()
    text = generate()
    if args.check:
        if OUT.read_text(encoding='utf-8') != text:
            print(f'FAIL: {OUT.relative_to(ROOT)} is out of date; run scripts/road_timing_table.py')
            return 1
        print(f'PASS: {OUT.relative_to(ROOT)} up to date')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
