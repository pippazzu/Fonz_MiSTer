#!/usr/bin/env python3
"""The board's trimmer pots as MiSTer OSD settings: one table, three outputs.

Each pot in POTS gets an OSD entry on the "Board adjustments" page and a
field in the MiSTer status word above bit 63 (status[103:64], read from
hps_io in mister/Fonz.sv). Code 0 of each field is the factory setting,
listed first and marked "(default)", so a fresh core or a reset of the OSD
settings (fields at 0) runs the board as the manual sets it. Codes 1.. are the other
settings in ascending order.

    python scripts/pot_settings.py           write the three outputs
    python scripts/pot_settings.py --check   fail if any of them is stale

Outputs:
  rtl/analog/fonz_pot_settings.vh  code -> setting functions and the
                                     field positions, for the models
  mister/Fonz.sv                     the page in the core's CONF_STR,
                                     between the "pot_settings.py" markers
  docs/POT_SETTINGS.md               the table for people

Settings are in the unit the model takes: ohms in circuit for the
rheostats, the wiper position in percent for VR-3 (a divider), seconds a
game for VR-10, the mixer's three positions for VR-13, and the full-grip
wiper voltage in mV for VR-11 (the throttle's upper limit), shown in the
OSD as how far up the picture the bike's wheels go at full grip. VR-12
(the lower limit) is not here: it is set from the manual's accelerator
drawing (docs/CONTROLS.md).
"""
import argparse
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
VH = ROOT / 'rtl' / 'analog' / 'fonz_pot_settings.vh'
DOC = ROOT / 'docs' / 'POT_SETTINGS.md'
SV = ROOT / 'mister' / 'Fonz.sv'
STATUS_BASE = 64          # first status bit of the pot fields
STATUS_BITS = 40          # width of the pot word, status[103:64]
PAGE = 2                  # OSD page (P1 is the Video page)
SV_BEGIN = '\t// BEGIN generated by scripts/pot_settings.py; do not edit by hand\n'
SV_END = '\t// END generated by scripts/pot_settings.py\n'


def ohm(v):
    if v == 0:
        return '0'
    if v >= 1000:
        s = f'{v / 1000:g}k'
    else:
        s = f'{v:g}'
    return s


def pct(v):
    return f'{v}%'


def sec(v):
    return f'{v} s'


VR13_NAMES = {0: '0', 1: '1k', 2: '2k'}


# VR-11: full-grip wiper voltage (mV) -> where the bike's wheels end up, in
# percent of the picture height from the bottom. The steady state of
# rtl/fonz_throttle.v: C77 sits above the clamp by the wiper's excess
# shared as the model's integer Euler steps K_IN / (K_IN + K_B) (13 / 435);
# TR10 sinks BETA x Ib from IC105 pin 3 (4.615 V behind 769 ohm), saturating
# at 0.85 V. The pulse is 8.4 ms x ln(5 / (5 - Vpin3)); the bike's top line
# follows it linearly through the two points the throttle header gives from
# the machine sim (12.7 ms: line 206, 4.8 ms: line 79), and its wheels are
# 28 lines lower. The picture is lines 13 to 257 (245 lines). This gives
# 61 % at the factory 3061 mV (the manual's drawing) and 67 % at 3286 mV
# (the manual's written 12 3/4 in), as the throttle header has them.
def vr11_percent(mv):
    k_in = (1 << 16) * 10**9 // 1000 // (100_000 * 47_000)
    k_b = (1 << 16) * 10**9 // 1000 // (3300 * 47_000)
    g_up, g_dn = 5000 * 10000 + 1000 * 10000, 1000 * 5000
    vth = 5000 * g_up / (g_up + g_dn)
    rth = 1000 * 5000 * 10000 / (g_up + g_dn)
    ib_ma = (mv - 1300) * k_in / (k_in + k_b) / 3300
    ic_ma = min(200 * ib_ma, (vth - 850) / rth)
    pin3 = vth - ic_ma * rth
    width = 8.4 * math.log(5 / (5 - pin3 / 1000))
    w_full, w_dark = 8.4 * math.log(5 / 2.84), 8.4 * math.log(5 / 1.1)
    top = 79 + (width - w_full) * (206 - 79) / (w_dark - w_full)
    return (257 - (top + 28)) / 245 * 100


def grip(mv):
    return f'{round(vr11_percent(mv))}%'

# key, OSD label, what it does, unit formatter, default, all settings
# (ascending; the default among them), where it is modelled.
POTS = [
    ('VR1', 'Own bike', 'player bike size (IC9, upper shape PROMs IC86/IC87; larger = smaller bike), 10k rheostat',
     ohm, 1800, [1000, 1200, 1500, 1800, 2200, 3300, 5000, 10000], 'rtl/analog/fonz_shape_oscillator.v'),
    ('VR9', 'Opp. bike', 'opponent bike size (IC106, lower shape PROMs IC49/IC50; larger = smaller bike), 10k rheostat',
     ohm, 1800, [1000, 1200, 1500, 1800, 2200, 3300, 5000, 10000], 'rtl/analog/fonz_shape_oscillator.v'),
    ('VR2', 'All bikes', 'size of all bikes (TR2 feed), 100 ohm rheostat; under 20 ohm the model step is unstable',
     ohm, 50, [25, 50, 75, 100], 'rtl/analog/fonz_shape_oscillator.v'),
    ('VR3', 'Crash road', 'road shape at the time of a crash, 10k divider (wiper %)',
     pct, 50, [0, 25, 50, 75, 100], 'rtl/analog/fonz_road_swing.v'),
    ('VR4', 'Swing width', 'road side-swing width, 2k rheostat',
     ohm, 1000, [0, 500, 1000, 1500, 2000], 'rtl/analog/fonz_road_swing.v'),
    ('VR5', 'Swing speed', 'road side-swing frequency (larger = slower), 500k rheostat',
     ohm, 250_000, [0, 125_000, 250_000, 375_000, 500_000], 'rtl/analog/fonz_road_swing.v'),
    ('VR6', 'Road widen', 'how much the road widens down the screen, 10k rheostat',
     ohm, 1000, [0, 1000, 2000, 3500, 5000, 7500, 10000], 'rtl/analog/fonz_road_timing.v'),
    ('VR7', 'Left kerb', 'left kerb width (TR7, IC102 pin 5), 10k rheostat',
     ohm, 5000, [0, 2500, 5000, 7500, 10000], 'rtl/analog/fonz_road_timing.v'),
    ('VR8', 'Right kerb', 'right kerb width (TR8, IC104 pin 5), 10k rheostat',
     ohm, 5000, [0, 2500, 5000, 7500, 10000], 'rtl/analog/fonz_road_timing.v'),
    ('VR10', 'Game time', 'play time (IC105B clock), 200k rheostat',
     sec, 70, [45, 55, 60, 70, 80, 90, 100], 'rtl/analog/fonz_556_timers.v'),
    ('VR13', 'Grey level', 'grey of the IC7 pin 12 video level, 2k (mixer)',
     lambda v: VR13_NAMES[v], 1, [0, 1, 2], 'rtl/fpga/fonz_video_mixer_fpga.v'),
    # Last, so the fields above keep their status bits from earlier builds.
    ('VR11', 'Grip height', 'throttle upper limit (full-grip wiper, mV): height of the bike\'s wheels '
     'at full grip, % of the picture (model estimate, vr11_percent); 61% is the manual\'s drawing, '
     '67% its written 12 3/4 in; 10k rheostat',
     grip, 3061, [2843, 3061, 3208, 3331, 3507, 3695, 3898], 'rtl/fonz_throttle.v'),
]

# VR-10: the manual gives about 70 s a game at the factory setting, and the
# model sets VR10 to 77.76k for that (rtl/analog/fonz_556_timers.v). The
# game time is proportional to RA + 2 RB = R101 3.3k + VR10 + 2 x R96 68k.
VR10_DEFAULT_OHM = 77_760
VR10_FIXED_OHM = 3_300 + 2 * 68_000


def vr10_ohm(seconds):
    return round((VR10_DEFAULT_OHM + VR10_FIXED_OHM) * seconds / 70) - VR10_FIXED_OHM


def codes(pot):
    """Settings in code order: the default first, then the rest ascending."""
    _, _, _, _, default, values, _ = pot
    assert default in values and values == sorted(values) and len(set(values)) == len(values)
    return [default] + [v for v in values if v != default]


def width(pot):
    return max(1, (len(codes(pot)) - 1).bit_length())


def fields():
    lsb = STATUS_BASE
    out = []
    for pot in POTS:
        w = width(pot)
        out.append((pot, lsb, w))
        lsb += w
    assert lsb <= STATUS_BASE + STATUS_BITS, 'the pot word is full: widen STATUS_BITS and the ports'
    return out


def label(pot, v):
    s = pot[3](v)
    return f'{s} (default)' if v == pot[4] else s


def render_vh():
    lines = [
        '// Generated by scripts/pot_settings.py; do not edit.',
        '// The board pots as OSD settings. Each field of `pots` (MiSTer status',
        f'// bits {STATUS_BASE} and up, minus {STATUS_BASE}) is a code; code 0 is the factory',
        '// setting. The functions give the setting for a code, in the unit the',
        '// model takes (ohms, percent, seconds, VR-13 position).',
    ]
    for pot, lsb, w in fields():
        key = pot[0]
        lines.append(f'localparam integer POT_{key}_LSB = {lsb - STATUS_BASE};')
        lines.append(f'localparam integer POT_{key}_W = {w};')
    lines.append(f'localparam integer POT_BITS = {sum(w for _, _, w in fields())};')
    for pot, lsb, w in fields():
        key = pot[0].lower()
        lines.append(f'// {pot[0]}: {pot[2]}')
        lines.append(f'function integer pot_{key}(input integer code);')
        lines.append('    case (code)')
        for i, v in enumerate(codes(pot)):
            lines.append(f'    {i}: pot_{key} = {v};')
        lines.append(f'    default: pot_{key} = {pot[4]};')
        lines.append('    endcase')
        lines.append('endfunction')
    # VR-10 in ohms as well
    lines.append('// VR10 in ohms for a code (game time scales with R101 + VR10 + 2 x R96).')
    lines.append('function integer pot_vr10_ohm(input integer code);')
    lines.append('    case (code)')
    pot10 = [p for p in POTS if p[0] == 'VR10'][0]
    for i, v in enumerate(codes(pot10)):
        lines.append(f'    {i}: pot_vr10_ohm = {vr10_ohm(v)};')
    lines.append(f'    default: pot_vr10_ohm = {VR10_DEFAULT_OHM};')
    lines.append('    endcase')
    lines.append('endfunction')
    return '\n'.join(lines) + '\n'


def osd_string():
    parts = [f'P{PAGE},Board adjustments']
    for pot, lsb, w in fields():
        bits = f'O[{lsb}]' if w == 1 else f'O[{lsb + w - 1}:{lsb}]'
        opts = ','.join(label(pot, v) for v in codes(pot))
        parts.append(f'P{PAGE}{bits},{pot[1]},{opts}')
    return ';'.join(parts) + ';'


def render_sv(text):
    """The pot page as CONF_STR lines of mister/Fonz.sv, one entry a line."""
    entries = osd_string().rstrip(';').split(';')
    block = ''.join(f'\t"{e};",\n' for e in entries)
    if SV_BEGIN not in text or SV_END not in text:
        raise SystemExit(f'{SV.relative_to(ROOT)}: the pot_settings.py markers are missing')
    head, rest = text.split(SV_BEGIN, 1)
    tail = rest.split(SV_END, 1)[1]
    return head + SV_BEGIN + block + SV_END + tail


def render_doc():
    lines = [
        '# Board pot settings in the OSD',
        '',
        '<!-- Generated by scripts/pot_settings.py; do not edit by hand. -->',
        '',
        'The logic board\'s trimmer pots are on the MiSTer OSD page "Board',
        'adjustments". Each entry starts at the factory setting, marked',
        '"(default)": the manual\'s "Details of logic board adjustments" page',
        'where it gives one, else the setting chosen from the footage or',
        'midway (docs/MISTER_CORE.md, "Pot settings"). Changing an entry takes',
        'effect at once, without a reset; the analogue networks then settle',
        'from where they were, as a real pot turned on a running board would.',
        '',
        "The settings live in status[103:64] of hps_io's 128-bit status word;",
        '`mister/Fonz.sv` passes them to the core, and its CONF_STR carries the',
        'page, written by the same script.',
        '',
        '| Pot | Status bits | Sets | Settings, in OSD order | Model |',
        '|---|---|---|---|---|',
    ]
    for pot, lsb, w in fields():
        bits = f'{lsb}' if w == 1 else f'{lsb + w - 1}:{lsb}'
        opts = ', '.join(label(pot, v) for v in codes(pot))
        lines.append(f'| VR-{pot[0][2:]} {pot[1]} | {bits} | {pot[2]} | {opts} | `{pot[6]}` |')
    lines += [
        '',
        'Which bike VR-1 and VR-9 size comes from the machine sim (12 November',
        '2026): VR-1 at 10k shrinks the player\'s bike, VR-9 at 10k the opponent\'s.',
        'docs/SHAPE_OSCILLATORS.md had them the other way round.',
        '',
        'VR-10 game times are set as resistance: VR10 = 217.06k x T / 70 s - 139.3k',
        '(70 s is the manual\'s 77.76k). VR-3 is a divider (R21 10k from +5 V,',
        'VR3 10k to ground); its wiper sets the level D3 holds the swing capacitor',
        'at in a crash. VR-13 picks one of the three mixer levels of',
        '`scripts/video_mixer_levels.py`.',
        '',
        'VR-11 (the throttle\'s upper limit) sets how far up the road the bike',
        'goes at full grip. Its settings are the full-grip wiper voltage of',
        '`rtl/fonz_throttle.v`; the OSD shows them as the height of the',
        'wheels in percent of the picture, worked out from the throttle model',
        '(`vr11_percent`), not measured. The factory 61% follows the manual\'s',
        'drawing; at the written 12 3/4 in (about 67%) the bike went too far',
        'up the road on the real board (12 November 2026). VR-12 (the lower',
        'limit) is not in the OSD: it is set from the manual\'s accelerator',
        'drawing (docs/CONTROLS.md).',
        '',
        'In the Verilator machine sim (sim/verilator/build.sh) the same word is',
        'the `pots=HEX` argument, bit 0 = status bit 64.',
        '',
    ]
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    outputs = [
        (VH, render_vh()),
        (SV, render_sv(SV.read_text(encoding='utf-8'))),
        (DOC, render_doc()),
    ]
    stale = []
    for path, text in outputs:
        old = path.read_text(encoding='utf-8') if path.exists() else None
        if old != text:
            if args.check:
                stale.append(path.relative_to(ROOT))
            else:
                path.write_text(text, encoding='utf-8', newline='\n')
                print(f'wrote {path.relative_to(ROOT)}')
    if stale:
        print('FAIL: stale, run scripts/pot_settings.py: ' + ', '.join(map(str, stale)))
        return 1
    if args.check:
        print('PASS: pot settings up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
