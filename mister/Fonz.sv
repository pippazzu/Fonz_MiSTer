	"P1O[23],Score overlay,On,Off;",
	"P1O[24],CRT picture,Native 4:3,3:4 squeeze;",
	// BEGIN generated by scripts/pot_settings.py; do not edit by hand
	"P2,Board adjustments;",
	"P2O[66:64],Own bike,1.8k (default),1k,1.2k,1.5k,2.2k,3.3k,5k,10k;",
	"P2O[69:67],Opp. bike,1.8k (default),1k,1.2k,1.5k,2.2k,3.3k,5k,10k;",
	"P2O[71:70],All bikes,50 (default),25,75,100;",
	"P2O[74:72],Crash road,50% (default),0%,25%,75%,100%;",
	"P2O[77:75],Swing width,1k (default),0,500,1.5k,2k;",
	"P2O[80:78],Swing speed,250k (default),0,125k,375k,500k;",
	"P2O[83:81],Road widen,1k (default),0,2k,3.5k,5k,7.5k,10k;",
	"P2O[86:84],Left kerb,5k (default),0,2.5k,7.5k,10k;",
	"P2O[89:87],Right kerb,5k (default),0,2.5k,7.5k,10k;",
	"P2O[92:90],Game time,70 s (default),45 s,55 s,60 s,80 s,90 s,100 s;",
	"P2O[94:93],Grey level,1k (default),0,2k;",
	"P2O[97:95],Grip height,61% (default),55%,65%,68%,72%,76%,80%;",
	// END generated by scripts/pot_settings.py
	"-;",
	"O[26:25],Throttle stick,Left up,None,Right up,Right down;",
	"O[27],Rumble on crash,On,Off;",
	"-;",
	"J1,Accelerate,-,Start,Coin;",
	"-;",
	"R[0],Reset and close OSD;",
	"V,v",`BUILD_DATE
};

wire         forced_scandoubler;
wire   [1:0] buttons;
wire [127:0] status;
wire  [21:0] gamma_bus;

wire         ioctl_download;
wire  [15:0] ioctl_index;
wire         ioctl_wr;
wire  [26:0] ioctl_addr;
wire   [7:0] ioctl_dout;

wire  [31:0] joystick_0;
wire  [15:0] joystick_l_analog_0, joystick_r_analog_0;
wire   [7:0] joystick_lt_analog_0, joystick_rt_analog_0;
wire  [15:0] rumble;

hps_io #(.CONF_STR(CONF_STR)) hps_io
(
	.clk_sys(clk_sys),
	.HPS_BUS(HPS_BUS),
	.EXT_BUS(),
	.gamma_bus(gamma_bus),

	.forced_scandoubler(forced_scandoubler),

	.buttons(buttons),
	.status(status),
	.status_menumask(16'd0),

	.ioctl_download(ioctl_download),
	.ioctl_index(ioctl_index),
	.ioctl_wr(ioctl_wr),
	.ioctl_addr(ioctl_addr),
	.ioctl_dout(ioctl_dout),
	.ioctl_wait(1'b0),

	.joystick_0(joystick_0),
	.joystick_l_analog_0(joystick_l_analog_0),
	.joystick_r_analog_0(joystick_r_analog_0),
	.joystick_lt_analog_0(joystick_lt_analog_0),
	.joystick_rt_analog_0(joystick_rt_analog_0),
	.joystick_0_rumble(rumble)
);

///////// Clock /////////

wire clk_sys;
pll pll
(
	.refclk(CLK_50M),
	.rst(0),
	.outclk_0(clk_sys)
);

///////// Core /////////

wire       ce_pix, hs, vs, hb, vb;
wire [7:0] grey;
wire       rst_core;

fonz_core #(.CLK_HZ(57_220_000)) fonz_core
(
	.clk(clk_sys),
	.reset_req(RESET | status[0] | buttons[1]),

	.ioctl_download(ioctl_download),
	.ioctl_index(ioctl_index[7:0]),
	.ioctl_wr(ioctl_wr),
	.ioctl_addr(ioctl_addr),
	.ioctl_dout(ioctl_dout),

	.joystick(joystick_0),
	.joystick_l_analog(joystick_l_analog_0),
	.joystick_r_analog(joystick_r_analog_0),
	.joystick_lt(joystick_lt_analog_0),
	.joystick_rt(joystick_rt_analog_0),
	.status(status),

	.ce_out(ce_pix),
	.grey(grey),
	.hs(hs),
	.vs(vs),
	.hb(hb),
	.vb(vb),
	.rumble(rumble),
	.rst(rst_core)
);

///////// Video /////////

// 374 active pixels a line in both CRT picture modes (rtl/mister/fonz_crt_out.v)
arcade_video #(.WIDTH(380), .DW(24)) arcade_video
(
	.clk_video(clk_sys),
	.ce_pix(ce_pix),

	.RGB_in({grey, grey, grey}),
	.HBlank(hb),
	.VBlank(vb),
	.HSync(hs),
	.VSync(vs),

	.CLK_VIDEO(CLK_VIDEO),
	.CE_PIXEL(CE_PIXEL),
	.VGA_R(VGA_R),
	.VGA_G(VGA_G),
	.VGA_B(VGA_B),
	.VGA_HS(VGA_HS),
	.VGA_VS(VGA_VS),
	.VGA_DE(VGA_DE),
	.VGA_SL(VGA_SL),

	.fx(status[5:3]),
	.forced_scandoubler(forced_scandoubler),
	.gamma_bus(gamma_bus)
);

// The user LED shows the ROM download
assign LED_USER = ioctl_download;

endmodule
