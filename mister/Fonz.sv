// Only the framework parts are here: hps_io (OSD, controls, ROM download,
// rumble), the 57.22 MHz PLL and arcade_video. The core itself, with its
// reset, PROM download, inputs and video out, is rtl/mister/fonz_core.v
// (docs/MISTER_CORE.md).
//
// Clock. clk_sys is 57.22 MHz (rtl/pll), four times the board's 14.305 MHz
// crystal: 50 MHz x 103 / 90 = 57.2222 MHz, 39 ppm high. The board's raster
// then runs at its own rates, 454 pixels a line (15.754 kHz) and 261 lines
// (60.36 Hz).

module emu
(
	`include "sys/emu_ports.vh"
);

///////// Ports this core does not use /////////

assign ADC_BUS  = 'Z;
assign USER_OUT = '1;
assign {UART_RTS, UART_TXD, UART_DTR} = 0;
assign {SD_SCK, SD_MOSI, SD_CS} = 'Z;
assign {SDRAM_DQ, SDRAM_A, SDRAM_BA, SDRAM_CLK, SDRAM_CKE, SDRAM_DQML, SDRAM_DQMH, SDRAM_nWE, SDRAM_nCAS, SDRAM_nRAS, SDRAM_nCS} = 'Z;
assign {DDRAM_CLK, DDRAM_BURSTCNT, DDRAM_ADDR, DDRAM_DIN, DDRAM_BE, DDRAM_RD, DDRAM_WE} = '0;

assign VGA_F1 = 0;
assign VGA_SCALER  = 0;
assign VGA_DISABLE = 0;
assign HDMI_FREEZE = 0;
assign HDMI_BLACKOUT = 0;
assign HDMI_BOB_DEINT = 0;

// No sound: the original's audio comes from a cassette player, which is not
// part of the board trace
assign AUDIO_S = 0;
assign AUDIO_L = 0;
assign AUDIO_R = 0;
assign AUDIO_MIX = 0;

assign LED_DISK = 0;
assign LED_POWER = 0;
assign BUTTONS = 0;

///////// Aspect ratio /////////

// The cabinet's tube stands portrait with horizontal scan lines: no
// rotation, a 3:4 picture (docs/VIDEO_TIMING.md, "Orientation")
wire [1:0] ar = status[122:121];

assign VIDEO_ARX = (!ar) ? 12'd3 : (ar - 1'd1);
assign VIDEO_ARY = (!ar) ? 12'd4 : 12'd0;

///////// OSD /////////

// Status bits 23-27 and 64-103: see docs/MISTER_CORE.md and
// docs/POT_SETTINGS.md.
// Bits 5:3 and 122:121 are this framework's video options. The board has
// no DIP switches, so there is no DIP menu.
`include "build_id.v"
localparam CONF_STR = {
	"Fonz;;",
	"-;",
	"P1,Video;",
	"P1-;",
	"P1O[122:121],Aspect ratio,Original,Full Screen,[ARC1],[ARC2];",
